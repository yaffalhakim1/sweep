// TestColumnsForDropsInOrder checks the responsive rule itself, because the
// thresholds are the only thing deciding what a user can see.
func TestColumnsForDropsInOrder(t *testing.T) {
	wide := columnsFor(900)
	if !wide.typeChip || !wide.size || !wide.modified || !wide.action {
		t.Errorf("a wide table dropped a column: %+v", wide)
	}
	mid := columnsFor(600)
	if !mid.typeChip {
		t.Error("a 600px table dropped the ecosystem column too early")
	}
	if mid.modified {
		t.Error("a 600px table kept the date column")
	}
	if !mid.size || !mid.action {
		t.Errorf("a 600px table dropped size or actions: %+v", mid)
	}
	slim := columnsFor(500)
	if slim.typeChip {
		t.Error("a 500px table kept the ecosystem column")
	}
	if !slim.size || !slim.action {
		t.Errorf("a 500px table dropped the size or the actions: %+v", slim)
	}
	narrow := columnsFor(420)
	if narrow.typeChip || narrow.modified {
		t.Errorf("a narrow table kept a column it cannot fit: %+v", narrow)
	}
	if !narrow.size || !narrow.action {
		t.Errorf("a narrow table dropped the size or the actions: %+v", narrow)
	}
	// The name column is never dropped: it is what the table is for.
	if !narrow.shows(sortName) || !mid.shows(sortName) || !wide.shows(sortName) {
		t.Error("the name column was dropped at some width")
	}
}

// writePNG writes a rendered frame, so it can be looked at.
func writePNG(path string, img *image.RGBA) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, img)
}
