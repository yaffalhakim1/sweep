// TestProjectNameNamesTheHoldingFolder is what tells two node_modules apart: the
// leaf name is the same for both, so the list has to name the project.
func TestProjectNameNamesTheHoldingFolder(t *testing.T) {
	cases := []struct {
		path string
		want string
	}{
		{`C:\Users\dev\waku\node_modules`, "waku"},
		{`/home/dev/web-app/.next`, "web-app"},
	}
	for _, c := range cases {
		if got := ProjectName(Artifact{Path: c.path}); got != c.want {
			t.Errorf("Project(%q) = %q, want %q", c.path, got, c.want)
		}
	}
}

// TestTypeLabelPrefersTheRule checks the ecosystem column says what a
// developer says: "Next.js" rather than "Node".
func TestTypeLabelPrefersTheRule(t *testing.T) {
	if got := TypeLabel(Artifact{Kind: Node, Rule: Rule{Label: "Next.js"}}); got != "Next.js" {
		t.Errorf("TypeLabel = %q, want the rule's own label", got)
	}
	// A rule with no label falls back to the kind rather than to an empty cell.
	if got := TypeLabel(Artifact{Kind: Node}); got != "Node" {
		t.Errorf("TypeLabel = %q, want the kind", got)
	}
}

// TestDormantNeedsRealTime checks the abandoned-project signal, which is the
// one claim the list makes about whether a folder is still in use.
func TestDormantNeedsRealTime(t *testing.T) {
	now := time.Now()
	if Dormant(Artifact{Touched: now.Add(-time.Hour)}, now) {
		t.Error("an hour-old artifact was called dormant")
	}
	if !Dormant(Artifact{Touched: now.Add(-DormantAfter - time.Hour)}, now) {
		t.Error("an artifact untouched for over three months was not called dormant")
	}
	// An artifact whose time is unknown is not dormant: the app does not know.
	if Dormant(Artifact{}, now) {
		t.Error("an artifact with no timestamp was called dormant")
	}
}

// TestCachesIsTheRegeneratedSubset checks the cache page's source: a cache is
// regenerated by the next run, which is why it is the cheapest space to take.
func TestCachesIsTheRegeneratedSubset(t *testing.T) {
	arts := []Artifact{
		{Path: "a/node_modules", Kind: Node, Rule: Rule{Name: "node_modules"}},
		{Path: "b/.turbo", Kind: Node, Rule: Rule{Name: ".turbo", Cache: true}},
		{Path: "c/__pycache__", Kind: Python, Rule: Rule{Name: "__pycache__", Cache: true}},
	}
	caches := Caches(arts)
	if len(caches) != 2 {
		t.Fatalf("Caches returned %d of %d", len(caches), len(arts))
	}
	for _, a := range caches {
		if !a.Rule.Cache {
			t.Errorf("%s is not a cache", a.Path)
		}
	}
	if !HasCache(arts) {
		t.Error("HasCache missed the caches")
	}
	if HasCache(arts[:1]) {
		t.Error("HasCache found a cache in a list of build output")
	}
}

// TestEveryRuleHasALabel checks the ecosystem column has something to say for
// every rule, rather than falling back to a bare kind on one of them.
