// Match returns the rule a directory matches, and whether one did. dir is
// the directory's full path and name its leaf name, which the walker
// already has, so matching costs no filesystem call of its own.
func Match(dir, name string) (Rule, bool) {
	for _, r := range rules {
		if r.Prefix {
			if !strings.HasPrefix(name, r.Name) {
				continue
			}
		} else if name != r.Name {
			continue
		}
		if r.Verify != nil && !r.Verify(dir) {
			continue
		}
		return r, true
	}
	return Rule{}, false
}

// hasFile reports whether dir holds one of the given files. It is how a
// generic directory name is confirmed to be a real build artifact.
func hasFile(names ...string) func(string) bool {
	return func(dir string) bool {
		for _, n := range names {
			if _, err := os.Stat(filepath.Join(dir, n)); err == nil {
				return true
			}
		}
		return false
	}
}

// hasSibling reports whether the directory's parent holds a file matching
// a pattern. A .NET project's obj sits beside its .csproj, never inside it.
func hasSibling(pattern string) func(string) bool {
	return func(dir string) bool {
		matches, err := filepath.Glob(filepath.Join(filepath.Dir(dir), pattern))
		return err == nil && len(matches) > 0
	}
}
